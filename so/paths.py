# DEFINE THE WORKSPACE ROOT (records/ IS VERSIONED IN GIT; IT IS NOT IN THE DATA FOLDER)
WORKSPACE_PATH_STR = os.path.dirname(os.path.dirname(os.path.abspath(__file__))).replace("\\", "/")
